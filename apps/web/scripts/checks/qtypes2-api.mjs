// Maths, picture and short-answer checking through the API.
import { readFileSync } from 'node:fs';
import { fileURLToPath as __path } from 'node:url';
const APP = __path(new URL('../..', import.meta.url)).replace(/[\\/]$/, '');
const base = 'http://localhost:8787', C = 'cmulde0g900147d341qn9mxlw';
const T = 'demo@teacher.com', TOM = 'tom@teacher.com', A = 'alice@student.com', B = 'bob@student.com', J = 'demo@student.com';
const H = (e) => ({ Authorization: `Bearer mock-token-${e}`, 'Content-Type': 'application/json' });
const call = async (who, path, body, method) => { const r = await fetch(base + path, { method: method ?? (body ? 'POST' : 'GET'), headers: H(who), body: body ? JSON.stringify(body) : undefined }); return { s: r.status, b: await r.json().catch(() => ({})) }; };
const out = {};
for (const q of (await call(T, '/api/core/quizzes')).b ?? []) if (q.title?.startsWith('Types2 API')) await call(T, `/api/core/quizzes/${q.id}`, null, 'DELETE');
const up = await fetch(`${base}/api/upload?filename=pic.png`, { method: 'POST', headers: { Authorization: `Bearer mock-token-${T}`, 'Content-Type': 'image/png' }, body: readFileSync(`${APP}/public/icon-192x192.png`) }).then((r) => r.json());
out.upload = up.url?.slice(0, 12);
const quiz = (await call(T, '/api/core/quizzes', { courseId: C, title: 'Types2 API' })).b;
const add = (q) => call(T, `/api/quizzes/${quiz.id}/questions`, { ...q, points: 1 });
const short = (await add({ type: 'SHORT', question: 'Capital of France?', accepted: ['Paris'] })).b;
const math = (await add({ type: 'MATH', question: 'Expand (x+1)^2.', accepted: ['x^2 + 2x + 1'] })).b;
const pic = (await add({ type: 'HOTSPOT', question: 'Tap the top left.', image: up.url, areas: [{ x: 0, y: 0, w: 30, h: 30 }] })).b;
out.made = [short.type, math.type, pic.type];
out.bad = [(await add({ type: 'MATH', question: 'x', accepted: ['2 +'] })).b.error, (await add({ type: 'HOTSPOT', question: 'x', image: 'https://evil.example/a.png', areas: [{ x: 1, y: 1, w: 9, h: 9 }] })).b.error];
await call(T, `/api/quizzes/${quiz.id}`, { status: 'PUBLISHED' }, 'PATCH');
const seen = (await call(A, `/api/core/quizzes/${quiz.id}`)).b;
out.studentSeesAreas = JSON.stringify(seen).includes('"areas"') || JSON.stringify(seen).includes('x^2 + 2x');
out.ask = seen.questions.map((q) => JSON.stringify(q.ask));
const sub = async (who, a) => (await call(who, `/api/core/quizzes/${quiz.id}/submit`, { answers: { [short.id]: a[0], [math.id]: a[1], [pic.id]: a[2] } })).b.score;
out.scores = [await sub(A, ['Paris', '(x+1)^2', '10,10']), await sub(B, ['paree', '\\frac{2x^2+4x+2}{2}', '80,80']), await sub(J, ['Paree', 'x^2+1', 'junk'])];
// The teacher's check of the short answers.
const list = (await call(T, `/api/quizzes/${quiz.id}/short-answers?questionId=${short.id}`)).b;
out.wrong = list.wrong;
out.ta = (await call(TOM, `/api/quizzes/${quiz.id}/short-answers?questionId=${short.id}`)).s;
out.student = (await call(A, `/api/quizzes/${quiz.id}/short-answers?questionId=${short.id}`)).s;
out.notShort = (await call(T, `/api/quizzes/${quiz.id}/short-answers?questionId=${math.id}`)).s;
const acc = await call(T, `/api/quizzes/${quiz.id}/short-answers`, { action: 'accept', questionId: short.id, answer: 'paree' });
out.accept = [acc.s, acc.b.accepted, acc.b.rescored];
const t = (await call(T, `/api/quizzes/${quiz.id}`)).b;
out.after = t.submissions.map((x) => `${x.student.name.split(' ')[0]}:${x.score}`).sort();
out.wrongAfter = (await call(T, `/api/quizzes/${quiz.id}/short-answers?questionId=${short.id}`)).b.wrong.length;
out.unaccept = (await call(T, `/api/quizzes/${quiz.id}/short-answers`, { action: 'unaccept', questionId: short.id, answer: 'Paree' })).b.rescored;
out.lastOne = (await call(T, `/api/quizzes/${quiz.id}/short-answers`, { action: 'unaccept', questionId: short.id, answer: 'Paris' })).b.error;
out.suggest = (await call(T, `/api/quizzes/${quiz.id}/short-answers/suggest`, { questionId: short.id })).s;
await call(T, `/api/quizzes/${quiz.id}`, { status: 'CLOSED' }, 'PATCH');
const res = (await call(B, `/api/quizzes/${quiz.id}/result`)).b;
out.result = res.questions.map((q) => `${q.type}:${q.credit}:${q.image ? 'img' : ''}:${q.areas ? q.areas.length : '-'}`);
await call(T, `/api/core/quizzes/${quiz.id}`, null, 'DELETE');
console.log(JSON.stringify(out, null, 1));
