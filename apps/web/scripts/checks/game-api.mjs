// The live quiz game through the API.
import { execSync } from 'node:child_process';
import { fileURLToPath as __path } from 'node:url';
const APP = __path(new URL('../..', import.meta.url)).replace(/[\\/]$/, '');
const base = 'http://localhost:8787', C = 'cmulde0g900147d341qn9mxlw';
const T = 'demo@teacher.com', A = 'alice@student.com', B = 'bob@student.com', J = 'demo@student.com';
const H = (e) => ({ Authorization: `Bearer mock-token-${e}`, 'Content-Type': 'application/json' });
// One retry: a kept-alive connection can go stale while the slow database commands run.
const send = (who, path, body, method) => fetch(base + path, { method: method ?? (body ? 'POST' : 'GET'), headers: H(who), body: body ? JSON.stringify(body) : undefined });
const call = async (who, path, body, method) => { const r = await send(who, path, body, method).catch(() => send(who, path, body, method)); return { s: r.status, b: await r.json().catch(() => ({})) }; };
const out = {};
for (const q of (await call(T, '/api/core/quizzes')).b ?? []) if (q.title?.startsWith('Game API')) await call(T, `/api/core/quizzes/${q.id}`, null, 'DELETE');
const quiz = (await call(T, '/api/core/quizzes', { courseId: C, title: 'Game API' })).b;
for (const [q, a] of [['Q1?', 'a'], ['Q2?', 'b'], ['Q3?', 'c']]) await call(T, `/api/quizzes/${quiz.id}/questions`, { question: q, options: ['a', 'b', 'c'], correctAnswer: a, points: 1 });
await call(T, `/api/quizzes/${quiz.id}/questions`, { type: 'SHORT', question: 'Not played', accepted: ['x'], points: 1 });
await call(T, `/api/quizzes/${quiz.id}`, { status: 'PUBLISHED' }, 'PATCH');
const start = await call(T, '/api/live/game', { courseId: C, quizId: quiz.id, seconds: 10 });
const gid = start.b.id;
out.start = start.s;
out.studentStart = (await call(A, '/api/live/game', { courseId: C, quizId: quiz.id })).s;
const seenA = (await call(A, '/api/live/game')).b;
out.lobby = [seenA.game?.status, seenA.game?.total, seenA.me?.joined];
const act = (who, body) => call(who, `/api/live/game/${gid}`, body);
await act(A, { action: 'join' }); await act(B, { action: 'join' });
out.names = (await call(T, `/api/live/game?courseId=${C}`)).b.names;
out.studentNext = (await act(A, { action: 'next' })).s;
const q = async (who) => (await call(who, '/api/live/game')).b;
await act(T, { action: 'next' });
let st = await q(A);
out.q1 = [st.game.status, st.question?.question, 'right' in (st.reveal ?? {}) || JSON.stringify(st).includes('correctAnswer')];
await act(A, { action: 'answer', questionId: st.question.id, answer: 'a' });
await act(B, { action: 'answer', questionId: st.question.id, answer: 'c' });
out.again = (await act(A, { action: 'answer', questionId: st.question.id, answer: 'b' })).s;
out.answered = (await call(T, `/api/live/game?courseId=${C}`)).b.game.answered;
await act(T, { action: 'reveal' });
st = await q(A);
out.reveal1 = [st.reveal?.right, st.reveal?.counts?.join(','), st.me.correct, st.me.points > 900, st.top.map((p) => `${p.name.split(' ')[0]}:${p.rank}`).join(' ')];
await act(T, { action: 'next' });
st = await q(A);
await act(A, { action: 'answer', questionId: st.question.id, answer: 'b' });
await act(B, { action: 'answer', questionId: st.question.id, answer: 'b' });
await act(T, { action: 'reveal' });
st = await q(A);
out.streak = [st.me.streak, st.top.find((p) => p.name.startsWith('Alice'))?.streak];
await act(T, { action: 'next' });
st = await q(B);
// John answers without joining first: he's put in the game.
await act(J, { action: 'answer', questionId: st.question.id, answer: 'c' });
await act(B, { action: 'answer', questionId: st.question.id, answer: 'c' });
await act(T, { action: 'next' }); // the last question: reveals and ends
const done = await q(A);
out.done = [done.game.status, done.top.map((p) => `${p.name.split(' ')[0]}:${p.score}:${p.rank}`).join(' '), done.me.streak];
const practised = execSync(`npx wrangler d1 execute universe-db --local --json --command "SELECT COUNT(*) AS n FROM practice_answers WHERE questionId IN (SELECT id FROM quiz_questions WHERE quizId='${quiz.id}')"`, { cwd: APP, encoding: 'utf8' });
out.savedAsPractice = JSON.parse(practised.slice(practised.indexOf('[')))[0].results[0].n;
out.afterEnd = (await act(A, { action: 'answer', questionId: st.question.id, answer: 'c' })).s;
// Time's up: a new game, its question started a minute ago.
const g2 = (await call(T, '/api/live/game', { courseId: C, quizId: quiz.id, seconds: 10 })).b.id;
out.oldGameEnded = (await call(T, `/api/live/game?courseId=${C}`)).b.game.id === g2;
await call(T, `/api/live/game/${g2}`, { action: 'next' });
const when = new Date(Date.now() - 60_000).toISOString().replace('Z', '+00:00');
execSync(`npx wrangler d1 execute universe-db --local --command "UPDATE live_games SET questionAt='${when}' WHERE id='${g2}'"`, { cwd: APP, stdio: 'ignore' });
const late = await call(A, `/api/live/game/${g2}`, { action: 'answer', questionId: (await q(A)).question.id, answer: 'a' });
out.late = [late.s, late.b.message ?? late.b.error];
await call(T, `/api/live/game/${g2}`, { action: 'end' });
await call(T, `/api/core/quizzes/${quiz.id}`, null, 'DELETE');
console.log(JSON.stringify(out, null, 1));
