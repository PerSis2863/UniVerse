import { launch } from '../browser-session.mjs';
const base = 'http://localhost:8787', C = 'cmulde0g900147d341qn9mxlw';
const token = 'mock-token-demo@teacher.com';
const me = await fetch(`${base}/api/core/auth/me`, { headers: { Authorization: `Bearer ${token}` } }).then((r) => r.json());
const browser = await launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
await ctx.addInitScript(([t, user]) => { localStorage.setItem('accessToken', t); localStorage.setItem('universe-auth', JSON.stringify({ state: { user }, version: 0 })); }, [token, me]);
const page = await ctx.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
const steps = []; page.on('response', (r) => { if (r.url().includes('/copy')) steps.push(r.status()); });
await page.goto(`${base}/teacher/blackboard?course=${C}`, { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Copy to a new term' }).click();
await page.getByLabel('New course code').fill('CS101-UI');
await page.getByLabel(/Move them by whole weeks/).check();
await page.getByLabel('Weeks to move').fill('26');
await page.getByRole('button', { name: 'Copy course' }).click();
await page.getByRole('button', { name: 'Open CS101-UI' }).waitFor({ timeout: 60_000 });
const doneText = await page.getByRole('dialog').innerText();
await page.getByRole('button', { name: 'Open CS101-UI' }).click();
await page.waitForTimeout(2000);
const header = await page.locator('h2').first().innerText();
const switcher = await page.locator('button:has-text("CS101-UI")').count();
console.log(JSON.stringify({ requests: steps.length, allOk: steps.every((s) => s === 200), done: doneText.includes('draft'), header, switcher, errors }));
// Team: add Tara as a teaching assistant on the copy, through the sheet.
await page.getByRole('button', { name: 'Teaching team' }).click();
await page.getByLabel('Their email address').fill('tara@teacher.com');
await page.getByLabel(/Teaching assistant/).check();
await page.getByRole('button', { name: 'Add to the team' }).click();
await page.getByText('Tara Mehta').waitFor({ timeout: 10_000 });
const role = await page.getByLabel('Role for Tara Mehta').inputValue();
console.log(JSON.stringify({ added: true, role, errors }));
await browser.close();
