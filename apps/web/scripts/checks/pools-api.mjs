// Pools and numbers that change per student, through the API.
const base = 'http://localhost:8787', C = 'cmulde0g900147d341qn9mxlw';
const T = 'demo@teacher.com', A = 'alice@student.com', B = 'bob@student.com';
const H = (e) => ({ Authorization: `Bearer mock-token-${e}`, 'Content-Type': 'application/json' });
const call = async (who, path, body, method) => { const r = await fetch(base + path, { method: method ?? (body ? 'POST' : 'GET'), headers: H(who), body: body ? JSON.stringify(body) : undefined }); return { s: r.status, b: await r.json().catch(() => ({})) }; };
const out = {};
for (const q of (await call(T, '/api/core/quizzes')).b ?? []) if (q.title?.startsWith('Pools API')) await call(T, `/api/core/quizzes/${q.id}`, null, 'DELETE');
const quiz = (await call(T, '/api/core/quizzes', { courseId: C, title: 'Pools API' })).b;
const add = (q) => call(T, `/api/quizzes/${quiz.id}/questions`, { points: 1, ...q });
await add({ question: 'Intro: pick yes', options: ['yes', 'no'], correctAnswer: 'yes' });
for (let k = 1; k <= 4; k++) await add({ question: `Pool question ${k}: pick yes`, options: ['yes', 'no'], correctAnswer: 'yes', pool: 'A' });
const car = await add({ type: 'NUMBER', question: 'A car drives {d} km in {t} hours. Average speed?', formula: 'd/t', vars: [{ name: 'd', min: 60, max: 300, step: 30 }, { name: 't', min: 2, max: 5, step: 1 }], tolerance: 0.05, unit: 'km/h' });
out.car = [car.s, car.b.correctAnswer];
out.badVar = (await add({ type: 'NUMBER', question: 'x', formula: 'd', vars: [{ name: 'd', min: 1, max: 2, step: 1 }] })).b.error;
out.pools = (await call(T, `/api/quizzes/${quiz.id}`, { pools: { A: 2, nonsense: 0 } }, 'PATCH')).b.pools;
await call(T, `/api/quizzes/${quiz.id}`, { status: 'PUBLISHED' }, 'PATCH');
const seenA = (await call(A, `/api/core/quizzes/${quiz.id}`)).b;
const again = (await call(A, `/api/core/quizzes/${quiz.id}`)).b;
const seenB = (await call(B, `/api/core/quizzes/${quiz.id}`)).b;
out.alice = seenA.questions.map((q) => q.question.slice(0, 22));
out.sameOnReload = JSON.stringify(again.questions.map((q) => q.id)) === JSON.stringify(seenA.questions.map((q) => q.id));
out.bob = seenB.questions.map((q) => q.question.slice(0, 22));
out.list = (await call(A, '/api/core/quizzes/student/my-quizzes')).b.find((q) => q.id === quiz.id)?._count?.questions;
const speed = (text) => { const m = /drives (\d+) km in (\d+) hours/.exec(text); return m ? Number(m[1]) / Number(m[2]) : NaN; };
const allIds = (await call(T, `/api/quizzes/${quiz.id}`)).b.questions.map((q) => q.id);
const answersFor = (seen, number) => Object.fromEntries(allIds.map((id) => { const q = seen.questions.find((x) => x.id === id); return [id, q?.type === 'NUMBER' ? String(number) : 'yes']; }));
const carA = seenA.questions.find((q) => q.type === 'NUMBER');
out.aliceSubmit = (await call(A, `/api/core/quizzes/${quiz.id}/submit`, { answers: answersFor(seenA, speed(carA.question)) })).b;
out.aliceSubmit = [out.aliceSubmit.score, out.aliceSubmit.maxScore];
// Bob answers with a number that's right for different numbers (most likely wrong for his).
const carB = seenB.questions.find((q) => q.type === 'NUMBER');
out.bobNumbersDiffer = carA.question !== carB.question;
out.bobSubmit = (await call(B, `/api/core/quizzes/${quiz.id}/submit`, { answers: answersFor(seenB, speed(carB.question) + 7) })).b;
out.bobSubmit = [out.bobSubmit.score, out.bobSubmit.maxScore];
await call(T, `/api/quizzes/${quiz.id}`, { status: 'CLOSED' }, 'PATCH');
const res = (await call(A, `/api/quizzes/${quiz.id}/result`)).b;
out.result = [res.questions.length, res.questions.find((q) => q.type === 'NUMBER')?.correctAnswer, res.questions.find((q) => q.type === 'NUMBER')?.question.slice(0, 30)];
const t = (await call(T, `/api/quizzes/${quiz.id}`)).b;
out.analysis = t.analysis.items.map((i) => `${i.right}:${i.answered}`).join(' ');
out.relay = (await call(T, `/api/classroom/relay?courseId=${C}`)).b.quizzes?.find((q) => q.id === quiz.id)?.problem;
const qid = t.questions[1].id;
out.unpool = (await call(T, `/api/quizzes/${quiz.id}/questions`, { qid, pool: '' }, 'PATCH')).s;
out.unpoolAfter = (await call(T, `/api/quizzes/${quiz.id}`)).b.questions[1].pool;
out.studentPatch = (await call(A, `/api/quizzes/${quiz.id}/questions`, { qid, pool: 'x' }, 'PATCH')).s;
await call(T, `/api/core/quizzes/${quiz.id}`, null, 'DELETE');
console.log(JSON.stringify(out, null, 1));
