// Writes cloudflare/api-routes.gen.ts: every API route in src/app/api, in the order Next.js matches
// them and with Next.js's own patterns, so cloudflare/api-direct.ts can run a route's handler without
// starting the Next.js server (see that file).
//
//   node scripts/gen-api-routes.mjs           rewrite the table (run after adding or removing a route)
//   node scripts/gen-api-routes.mjs --check   exit 1 if the table is out of date (src/lib/api-routes.test.ts)
//
// The build runs it too (package.json "build"), and with --env also writes the public settings
// (NEXT_PUBLIC_…) Next.js bakes into its server code, so the direct path sees the same values.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const { getSortedRoutes } = require('next/dist/shared/lib/router/utils/sorted-routes');
const { getRouteRegex } = require('next/dist/shared/lib/router/utils/route-regex');

const API = join(root, 'src/app/api');
const OUT = join(root, 'cloudflare/api-routes.gen.ts');
const ENV_OUT = join(root, 'cloudflare/next-public.gen.ts');

function routeFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return e.name.startsWith('_') ? [] : routeFiles(p);
    return e.name === 'route.ts' ? [p] : [];
  });
}

// "/api/a/(group)/[id]" → "/api/a/[id]": route groups don't appear in the address.
const toRoute = (file) => '/' + relative(join(root, 'src/app'), dirname(file)).split(sep).filter((s) => !/^\(.*\)$/.test(s)).join('/');

export function table() {
  const byRoute = new Map(routeFiles(API).map((f) => [toRoute(f), f]));
  const rows = getSortedRoutes([...byRoute.keys()]).map((route) => {
    const { re, groups } = getRouteRegex(route);
    const params = Object.entries(groups).sort((a, b) => a[1].pos - b[1].pos).map(([name, g]) => [name, g.repeat]);
    const spec = relative(join(root, 'cloudflare'), byRoute.get(route)).split(sep).join('/').replace(/\.ts$/, '');
    // `as string`: the bundler still sees (and bundles) the path; TypeScript doesn't follow it, since the
    // routes are checked with the app's own settings (tsconfig.json), not the Worker's.
    return `  [${JSON.stringify(route)}, ${JSON.stringify(re.source)}, ${JSON.stringify(params)}, () => import(${JSON.stringify(spec)} as string)],`;
  });
  return `// Generated by scripts/gen-api-routes.mjs from src/app/api (${rows.length} routes, in Next.js's match order). Don't edit.
// [route, pattern, params (name, catch-all), the route's module]
export type ApiRoute = [route: string, pattern: string, params: [name: string, many: boolean][], load: () => Promise<Record<string, unknown>>];

export const API_ROUTES: ApiRoute[] = [
${rows.join('\n')}
];
`;
}

function publicEnv() {
  // The same files and variables Next.js reads when it builds (.env, .env.production, the build's environment).
  createRequire(require.resolve('next/package.json'))('@next/env').loadEnvConfig(root, false, { info: () => {}, error: () => {} });
  const vars = Object.fromEntries(Object.keys(process.env).filter((k) => k.startsWith('NEXT_PUBLIC_')).sort().map((k) => [k, process.env[k]]));
  return `// Written by scripts/gen-api-routes.mjs --env during the build: the public settings (NEXT_PUBLIC_…)
// Next.js bakes into its server code, for the routes cloudflare/api-direct.ts runs. Empty in the repository.
export const NEXT_PUBLIC: Record<string, string> = ${JSON.stringify(vars, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = table();
  if (process.argv.includes('--check')) {
    const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (now !== next) {
      console.error('cloudflare/api-routes.gen.ts is out of date: run node scripts/gen-api-routes.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    if (process.argv.includes('--env')) writeFileSync(ENV_OUT, publicEnv());
    console.log(`API routes: ${next.split('\n').filter((l) => l.startsWith('  [')).length}`);
  }
}
