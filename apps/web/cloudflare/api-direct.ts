// Runs the app's API routes (src/app/api/**/route.ts) without starting the Next.js server.
//
// On a fresh Worker, the first request that needs Next.js makes it parse its whole server bundle
// (~32 MB: every page and route; 0.8–1.5 s of CPU in production, where Workers Free allows 10 ms), and
// requests that arrive meanwhile are cut off ("Couldn't load…"). An API route only needs its own code
// (all 434 together are ~3.6 MB), so they're run from here. Pages built ahead of time are already
// served from the cache without Next.js (OpenNext's cache interception); the light path (fast-api.ts)
// still answers the busiest calls with plain SQL first.
//
// It behaves like Next.js's own route handling: the same routes in the same match order with Next.js's
// own patterns (api-routes.gen.ts, made with Next.js's code by scripts/gen-api-routes.mjs), parameters
// decoded the same way, the same response headers from next.config.ts, and the same environment
// (OpenNext's request context, NEXT_PUBLIC_ values from the build). Anything else is left to Next.js:
// methods a route doesn't export (Next.js answers 405, HEAD and OPTIONS itself), addresses ending in
// "/" (Next.js redirects them), parameters that can't be decoded, and routes that fail to load.
import { securityHeaders } from '../security-headers';
import { matchApiRoute } from './api-match';
import { NEXT_PUBLIC } from './next-public.gen';
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- the file only exists after a build
// @ts-ignore: generated by `opennextjs-cloudflare build`
import { runWithCloudflareRequestContext } from '../.open-next/cloudflare/init.js';

type Handler = (request: Request, context: { params: Promise<Record<string, string | string[]>> }) => unknown;
type RunInContext = <T>(request: Request, env: unknown, ctx: ExecutionContext, fn: () => Promise<T>) => Promise<T>;

const METHODS = new Set(['GET', 'POST', 'PUT', 'PATCH', 'DELETE']);

// next.config.ts headers(): the security headers on everything, the page policy (CSP) on all but
// uploaded files and certificate pages; and the Vary header Next.js puts on every response. A header the
// route sets itself wins, as in Next.js.
const OWN_CSP = /^\/api\/(files\/|core\/impact\/certificates\/)/;
const VARY = { key: 'Vary', value: 'rsc, next-router-state-tree, next-router-prefetch, next-router-segment-prefetch' };
function withConfigHeaders(res: Response, pathname: string): Response {
  const add = [...securityHeaders, VARY].filter((h) => !res.headers.has(h.key) && (h.key !== 'Content-Security-Policy' || !OWN_CSP.test(pathname)));
  if (!add.length) return res;
  const out = res.status === 101 ? res : new Response(res.body, res);
  for (const h of add) out.headers.set(h.key, h.value);
  return out;
}

// The build's public settings, for code that reads them (Next.js bakes them in); a value set on the
// Worker itself wins.
let publicEnv = false;
function usePublicEnv() {
  if (publicEnv) return;
  publicEnv = true;
  for (const [key, value] of Object.entries(NEXT_PUBLIC)) process.env[key] ??= value;
}

/** The route's answer, or null to let Next.js answer. */
export async function apiDirect(request: Request, url: URL, env: unknown, ctx: ExecutionContext): Promise<Response | null> {
  if (!METHODS.has(request.method) || url.pathname.endsWith('/')) return null;
  let hit: ReturnType<typeof matchApiRoute>;
  try {
    hit = matchApiRoute(url.pathname);
  } catch {
    return null; // a parameter that isn't valid %-encoding: Next.js answers
  }
  if (!hit) return null;
  const route = hit;
  let handler: Handler | undefined;
  try {
    handler = (await route.load())[request.method] as Handler | undefined;
  } catch (e) {
    console.error(`direct API: ${url.pathname} failed to load:`, e);
    return null;
  }
  if (typeof handler !== 'function') return null;
  const run = handler;
  const res = await (runWithCloudflareRequestContext as RunInContext)(request, env, ctx, async () => {
    usePublicEnv();
    try {
      const out = await run(request, { params: Promise.resolve(route.params) });
      if (out instanceof Response) return out;
      console.error(`${request.method} ${url.pathname}: the route returned no response`);
    } catch (e) {
      console.error(`${request.method} ${url.pathname} failed:`, e);
    }
    // What Next.js answers when a route throws or returns nothing.
    return new Response(null, { status: 500 });
  });
  return withConfigHeaders(res, url.pathname);
}
