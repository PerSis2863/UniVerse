interface Env {
  ASSETS?: Fetcher;
  REALTIME: DurableObjectNamespace<RealtimeHub>;
  BOARDS?: DurableObjectNamespace<BoardRoom>;
  API_RATE_LIMITER?: RateLimit; // per signed-in user (or per IP when signed out)
  IP_RATE_LIMITER?: RateLimit; // per IP, generous: stops floods from one address
  COSTLY_RATE_LIMITER?: RateLimit; // per user, for AI, email and uploads
  [key: string]: unknown;
}

// Endpoints that cost money or send email per call.
const COSTLY = /^\/api\/(ai|summarize|premium\/ai-report|support|upload|core\/files\/upload|chat\/translate-draft|chat\/conversations\/[^/]+\/translate|tutor\/(?!cards)[^/]+\/(ask|practice|flashcards|sources))(\/|$)/;

const tooMany = () =>
  Response.json({ error: 'Too many requests. Please wait a minute and try again.' }, { status: 429, headers: { 'Retry-After': '60' } });

/**
 * Rate limits for the API and live updates. Keyed by the signed-in user (the end of their token)
 * so a whole campus behind one Wi-Fi address isn't treated as one person, plus a generous
 * per-address cap against floods. Limiter checks are free and don't count as requests.
 */
async function rateLimited(request: Request, url: URL, env: Env): Promise<boolean> {
  const ip = request.headers.get('cf-connecting-ip') ?? 'unknown';
  const token = request.headers.get('authorization')?.slice(-40);
  // Live connections can't send headers: they carry the user (and a one-time ticket) in the
  // address, so count them per user too, not per shared campus address.
  const live = url.pathname === '/realtime' ? url.searchParams.get('user') : url.pathname === '/board-live' ? url.searchParams.get('ticket') : null;
  const who = token ? `u:${token}` : live ? `live:${live.slice(0, 80)}` : `ip:${ip}`;
  const checks: Promise<{ success: boolean }>[] = [];
  if (env.IP_RATE_LIMITER) checks.push(env.IP_RATE_LIMITER.limit({ key: ip }));
  if (env.API_RATE_LIMITER) checks.push(env.API_RATE_LIMITER.limit({ key: who }));
  if (env.COSTLY_RATE_LIMITER && request.method !== 'GET' && COSTLY.test(url.pathname)) checks.push(env.COSTLY_RATE_LIMITER.limit({ key: who }));
  return (await Promise.all(checks)).some((r) => !r.success);
}

/**
 * Pages (HTML and in-app navigation data) come with Next's `s-maxage=…, stale-while-revalidate=…`,
 * meant for a shared cache. Browsers that honour stale-while-revalidate (Safari) could then show a
 * copy from before the last update, even after a refresh, and that copy points at files the update
 * removed. `no-cache` makes the browser check each time (a cheap 304 when nothing changed).
 */
function revalidatePages(request: Request, res: Response): Response {
  const type = res.headers.get('content-type') ?? '';
  if (!/^text\/(html|x-component)/.test(type) || !/s-maxage|stale-while-revalidate/.test(res.headers.get('cache-control') ?? '')) return res;
  // Unchanged since the browser's copy: just say so.
  const etag = res.headers.get('etag');
  if (etag && request.headers.get('if-none-match') === etag) return new Response(null, { status: 304, headers: { ETag: etag, 'Cache-Control': 'no-cache' } });
  const out = new Response(res.body, res);
  out.headers.set('Cache-Control', 'no-cache');
  return out;
}

// The build these pages belong to (public/BUILD_ID), read once per instance: cached pages are kept
// per build, so a deploy never serves pages that point at the previous build's files.
let buildId: Promise<string | null> | null = null;
function currentBuild(origin: string, env: Env) {
  buildId ??= (env.ASSETS ? env.ASSETS.fetch(`${origin}/BUILD_ID`).then((r) => (r.ok ? r.text() : null)).then((t) => t?.trim() || null) : Promise.resolve(null)).catch(() => {
    buildId = null;
    return null;
  });
  return buildId;
}

/**
 * Pages that are the same for everyone (Next.js built them ahead of time: the home page, sign-in,
 * the dashboards' shells, legal pages) are kept in Cloudflare's cache near the visitor. A repeat
 * visit is then answered without starting the Next.js app at all: a faster first screen, and no
 * CPU time for the free plan's limit. In-app navigation data (RSC requests) still goes to Next.js.
 */
async function edgeCachedPage(request: Request, url: URL, env: Env, ctx: ExecutionContext, render: () => Promise<Response>): Promise<Response> {
  const plain = request.method === 'GET' && !request.headers.has('rsc') && !request.headers.has('next-router-prefetch') && !request.headers.has('authorization') && !request.headers.has('range');
  const build = plain ? await currentBuild(url.origin, env) : null;
  if (!build) return revalidatePages(request, await render());
  const cache = (caches as unknown as { default: Cache }).default;
  const key = new Request(`${url.origin}${url.pathname}?__build=${encodeURIComponent(build)}`);
  const hit = await cache.match(key).catch(() => undefined);
  if (hit) {
    const etag = hit.headers.get('etag');
    if (etag && request.headers.get('if-none-match') === etag) return new Response(null, { status: 304, headers: { ETag: etag, 'Cache-Control': 'no-cache' } });
    const out = new Response(hit.body, hit);
    out.headers.set('Cache-Control', 'no-cache');
    return out;
  }
  const res = await render();
  const sameForEveryone = res.status === 200 && res.headers.get('x-nextjs-prerender') === '1' && /^text\/html/.test(res.headers.get('content-type') ?? '') && /s-maxage/.test(res.headers.get('cache-control') ?? '') && !res.headers.has('set-cookie');
  if (sameForEveryone) {
    const copy = new Response(res.clone().body, res);
    copy.headers.set('Cache-Control', 'public, max-age=86400');
    ctx.waitUntil(cache.put(key, copy).catch(() => {}));
  }
  return revalidatePages(request, res);
}

const TICKET_TTL_MS = 60_000;
const MAX_SOCKETS = 20; // per user: app + a few browser tabs

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    // Stripe's webhook is signed and comes from Stripe's servers, so it's never rate limited.
    if ((url.pathname.startsWith('/api/') && !url.pathname.startsWith('/api/webhooks/')) || url.pathname === '/realtime' || url.pathname === '/board-live') {
      if (await rateLimited(request, url, env)) return tooMany();
    }
    if (url.pathname === '/realtime') {
      if (request.headers.get('Upgrade')?.toLowerCase() !== 'websocket') return new Response('Expected a WebSocket', { status: 426 });
      const user = url.searchParams.get('user');
      if (!user || !url.searchParams.get('ticket') || !env.REALTIME) return new Response('Forbidden', { status: 403 });
      return env.REALTIME.get(env.REALTIME.idFromName(user)).fetch(request);
    }
    if (url.pathname === '/board-live') {
      if (request.headers.get('Upgrade')?.toLowerCase() !== 'websocket') return new Response('Expected a WebSocket', { status: 426 });
      const board = url.searchParams.get('board');
      if (!board || !url.searchParams.get('ticket') || !env.BOARDS) return new Response('Forbidden', { status: 403 });
      return env.BOARDS.get(env.BOARDS.idFromName(board)).fetch(request);
    }
    const fast = url.pathname.startsWith('/api/') ? await fastApi(request, url, env, ctx, (r) => nextApp.fetch(r, env, ctx)) : null;
    if (fast) return fast;
    // One address for the site: www.universeimpact.com and universeimpact.com were both in use,
    // each with its own sign-in (saved per address), offline copy and cache.
    if (url.hostname.startsWith('www.') && (request.method === 'GET' || request.method === 'HEAD') && !url.pathname.startsWith('/api/')) {
      return Response.redirect(`${url.protocol}//${url.host.slice(4)}${url.pathname}${url.search}`, 301);
    }
    if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/_next/')) return revalidatePages(request, await nextApp.fetch(request, env, ctx));
    return edgeCachedPage(request, url, env, ctx, () => nextApp.fetch(request, env, ctx));
  },

  async scheduled(controller: ScheduledController, env: Env, ctx: ExecutionContext) {
    // Run the job inside the Next.js app (where the database code lives). The random token only
    // exists in this isolate, so the route can't be triggered from outside.
    const token = crypto.randomUUID();
    (globalThis as { __universeCronToken?: string }).__universeCronToken = token;
    const res: Response = await nextApp.fetch(
      new Request('https://universeimpact.com/api/cron/daily', { method: 'POST', headers: { 'x-cron-token': token } }),
      env,
      ctx,
    );
    console.log(`cron ${controller.cron}: ${res.status} ${await res.text()}`);
    if (!res.ok) throw new Error(`Daily job failed with ${res.status}`);
  },
};

/**
 * One per user: holds that user's open WebSockets (hibernating while idle, so an open tab costs
 * nothing between events) and forwards "something changed" events to them.
 */
export class RealtimeHub extends DurableObject<Env> {
  constructor(ctx: DurableObjectState, env: Env) {
    super(ctx, env);
    // Keep-alive pings are answered without waking the object.
    this.ctx.setWebSocketAutoResponse(new WebSocketRequestResponsePair('ping', 'pong'));
  }

  async fetch(request: Request): Promise<Response> {
    const url = new URL(request.url);

    if (url.pathname === '/ticket' && request.method === 'POST') {
      const now = Date.now();
      const stale = [...(await this.ctx.storage.list<number>({ prefix: 'ticket:' }))].filter(([, exp]) => exp < now).map(([k]) => k);
      if (stale.length) await this.ctx.storage.delete(stale.slice(0, 128));
      const ticket = crypto.randomUUID();
      await this.ctx.storage.put(`ticket:${ticket}`, Date.now() + TICKET_TTL_MS);
      return Response.json({ ticket });
    }

    if (url.pathname === '/publish' && request.method === 'POST') {
      const message = await request.text();
      let sockets = 0;
      for (const ws of this.ctx.getWebSockets()) {
        try {
          ws.send(message);
          sockets++;
        } catch {
          /* closing */
        }
      }
      // How many tabs got it: > 0 means the user has UniVerse open right now.
      return Response.json({ sockets });
    }

    if (url.pathname === '/realtime') {
      const key = `ticket:${url.searchParams.get('ticket')}`;
      const expires = await this.ctx.storage.get<number>(key);
      if (!expires) return new Response('Forbidden', { status: 403 });
      await this.ctx.storage.delete(key); // single use
      if (expires < Date.now()) return new Response('Forbidden', { status: 403 });

      const open = this.ctx.getWebSockets();
      if (open.length >= MAX_SOCKETS) open[0].close(4000, 'Too many connections');
      const { 0: client, 1: server } = new WebSocketPair();
      this.ctx.acceptWebSocket(server);
      server.send(JSON.stringify({ type: 'hello' }));
      return new Response(null, { status: 101, webSocket: client });
    }

    return new Response('Not found', { status: 404 });
  }

  async webSocketMessage() {
    // Clients only send pings (auto-answered above).
  }

  async webSocketClose(ws: WebSocket, code: number) {
    try {
      ws.close(code === 1005 || code === 1006 ? 1000 : code);
    } catch {
      /* already closed */
    }
  }
}

// ─── Whiteboards ─────────────────────────────────────────────────────────────────────────────────

/** Who is on a board socket (kept on the socket so it survives hibernation). */
interface BoardPeer {
  sid: string; // this connection
  userId: string;
  name: string;
  avatar: string | null;
  color: string;
  canEdit: boolean;
}

/** The parts of an Excalidraw element the server needs to merge edits. */
interface BoardElement {
  id: string;
  version: number;
  versionNonce: number;
  isDeleted?: boolean;
  [key: string]: unknown;
}

interface BoardFile {
  id: string;
  mimeType: string;
  url: string; // an uploaded file (/api/files/… or the R2 files domain), never inline data
  created: number;
}

const MAX_ELEMENTS = 20_000;
const MAX_ELEMENT_BYTES = 256 * 1024; // one shape (a long freehand stroke is the biggest)
const MAX_FILES = 300;
const MAX_BOARD_SOCKETS = 60;
const PEER_COLORS = ['#6366f1', '#ec4899', '#f59e0b', '#10b981', '#0ea5e9', '#ef4444', '#8b5cf6', '#14b8a6', '#f97316', '#84cc16'];

/**
 * One per whiteboard: holds the board's shapes and pictures and everyone who has it open.
 * People edit locally and send the shapes they changed; the room keeps the newest version of each
 * shape (Excalidraw's version / versionNonce rules, so everyone ends up with the same drawing) and
 * passes the changes and live cursors on to the others. Viewers can watch but their edits are
 * ignored. Access is checked by the app, which hands out one-time tickets (/api/boards/[id]/ticket).
 */
export class BoardRoom extends DurableObject<Env> {
  private elementCount: number | undefined; // counted on first need after each wake-up

  constructor(ctx: DurableObjectState, env: Env) {
    super(ctx, env);
    this.ctx.setWebSocketAutoResponse(new WebSocketRequestResponsePair('ping', 'pong'));
  }

  private peers(): { ws: WebSocket; peer: BoardPeer }[] {
    const out: { ws: WebSocket; peer: BoardPeer }[] = [];
    for (const ws of this.ctx.getWebSockets()) {
      const peer = ws.deserializeAttachment() as BoardPeer | null;
      if (peer) out.push({ ws, peer });
    }
    return out;
  }

  private broadcast(message: unknown, except?: WebSocket) {
    const text = JSON.stringify(message);
    for (const ws of this.ctx.getWebSockets()) {
      if (ws === except) continue;
      try {
        ws.send(text);
      } catch {
        /* closing */
      }
    }
  }

  private presence() {
    return this.peers().map(({ peer }) => ({ sid: peer.sid, userId: peer.userId, name: peer.name, avatar: peer.avatar, color: peer.color, canEdit: peer.canEdit }));
  }

  async fetch(request: Request): Promise<Response> {
    const url = new URL(request.url);

    // From the app: a one-time ticket for someone allowed on the board.
    if (url.pathname === '/ticket' && request.method === 'POST') {
      const who = (await request.json()) as Omit<BoardPeer, 'sid' | 'color'>;
      const now = Date.now();
      const stale = [...(await this.ctx.storage.list<{ exp: number }>({ prefix: 'ticket:' }))].filter(([, t]) => t.exp < now).map(([k]) => k);
      if (stale.length) await this.ctx.storage.delete(stale.slice(0, 128));
      const ticket = crypto.randomUUID();
      await this.ctx.storage.put(`ticket:${ticket}`, { ...who, exp: now + TICKET_TTL_MS });
      return Response.json({ ticket });
    }

    // From the app: access changed (someone removed, a role or the link setting changed) or the
    // board was deleted. Matching people are disconnected; the app reconnects them if still allowed.
    if (url.pathname === '/kick' && request.method === 'POST') {
      const { userIds, all, wipe } = (await request.json()) as { userIds?: string[]; all?: boolean; wipe?: boolean };
      for (const { ws, peer } of this.peers()) {
        if (all || userIds?.includes(peer.userId)) {
          try {
            ws.close(wipe ? 4004 : 4003, wipe ? 'Board deleted' : 'Access changed');
          } catch {
            /* closed */
          }
        }
      }
      if (wipe) {
        await this.ctx.storage.deleteAll();
        this.elementCount = 0;
      }
      return Response.json({ ok: true });
    }

    // From the app: the drawing, for a copy of the board.
    if (url.pathname === '/snapshot' && request.method === 'GET') {
      return Response.json(await this.snapshot());
    }

    // From the app: fill a new board (a copy).
    if (url.pathname === '/seed' && request.method === 'POST') {
      const { elements, files } = (await request.json()) as { elements: BoardElement[]; files: BoardFile[] };
      const batch: Record<string, unknown> = {};
      for (const el of elements.slice(0, MAX_ELEMENTS)) if (validElement(el)) batch[`el:${el.id}`] = el;
      for (const f of files.slice(0, MAX_FILES)) if (validFile(f)) batch[`file:${f.id}`] = f;
      const entries = Object.entries(batch);
      for (let i = 0; i < entries.length; i += 128) await this.ctx.storage.put(Object.fromEntries(entries.slice(i, i + 128)));
      this.elementCount = undefined;
      return Response.json({ ok: true });
    }

    if (url.pathname === '/board-live') {
      const key = `ticket:${url.searchParams.get('ticket')}`;
      const who = await this.ctx.storage.get<Omit<BoardPeer, 'sid' | 'color'> & { exp: number }>(key);
      if (!who) return new Response('Forbidden', { status: 403 });
      await this.ctx.storage.delete(key); // single use
      if (who.exp < Date.now()) return new Response('Forbidden', { status: 403 });

      const open = this.ctx.getWebSockets();
      if (open.length >= MAX_BOARD_SOCKETS) return new Response('This board is full', { status: 429 });
      const used = new Set(this.peers().map(({ peer }) => peer.color));
      const color = PEER_COLORS.find((c) => !used.has(c)) ?? PEER_COLORS[open.length % PEER_COLORS.length];
      const peer: BoardPeer = { sid: crypto.randomUUID().slice(0, 8), userId: who.userId, name: who.name, avatar: who.avatar, color, canEdit: who.canEdit };

      const { 0: client, 1: server } = new WebSocketPair();
      this.ctx.acceptWebSocket(server);
      server.serializeAttachment(peer);
      const { elements, files } = await this.snapshot();
      server.send(JSON.stringify({ type: 'init', me: peer, elements, files, peers: this.presence() }));
      this.broadcast({ type: 'peers', peers: this.presence() }, server);
      return new Response(null, { status: 101, webSocket: client });
    }

    return new Response('Not found', { status: 404 });
  }

  private async snapshot() {
    const [els, files] = await Promise.all([
      this.ctx.storage.list<BoardElement>({ prefix: 'el:' }),
      this.ctx.storage.list<BoardFile>({ prefix: 'file:' }),
    ]);
    return { elements: [...els.values()], files: [...files.values()] };
  }

  async webSocketMessage(ws: WebSocket, raw: string | ArrayBuffer) {
    const peer = ws.deserializeAttachment() as BoardPeer | null;
    if (!peer || typeof raw !== 'string') return;
    let msg: { type?: string; [key: string]: unknown };
    try {
      msg = JSON.parse(raw);
    } catch {
      return;
    }

    if (msg.type === 'cursor') {
      // Where someone's pointer is: passed on, never stored.
      const { x, y, tool, button, selected } = msg as { x?: unknown; y?: unknown; tool?: unknown; button?: unknown; selected?: unknown };
      if (typeof x !== 'number' || typeof y !== 'number' || !Number.isFinite(x) || !Number.isFinite(y)) return;
      this.broadcast({
        type: 'cursor',
        sid: peer.sid,
        x,
        y,
        tool: tool === 'laser' ? 'laser' : 'pointer',
        button: button === 'down' ? 'down' : 'up',
        selected: Array.isArray(selected) ? selected.filter((s) => typeof s === 'string').slice(0, 200) : [],
      }, ws);
      return;
    }

    if (!peer.canEdit) return; // viewers watch only

    if (msg.type === 'update' && Array.isArray(msg.elements)) {
      const incoming = (msg.elements as BoardElement[]).filter(validElement);
      if (!incoming.length) return;
      const current = new Map<string, BoardElement>();
      for (let i = 0; i < incoming.length; i += 128) {
        for (const [k, v] of await this.ctx.storage.get<BoardElement>(incoming.slice(i, i + 128).map((e) => `el:${e.id}`))) current.set(k, v);
      }
      const accepted: BoardElement[] = [];
      for (const el of incoming) {
        const have = current.get(`el:${el.id}`);
        if (!have) {
          this.elementCount ??= (await this.ctx.storage.list({ prefix: 'el:' })).size;
          if (this.elementCount >= MAX_ELEMENTS) continue;
          this.elementCount++;
        } else if (!(el.version > have.version || (el.version === have.version && el.versionNonce < have.versionNonce))) {
          continue; // we already have this edit or a newer one
        }
        accepted.push(el);
      }
      if (!accepted.length) return;
      for (let i = 0; i < accepted.length; i += 128) {
        await this.ctx.storage.put(Object.fromEntries(accepted.slice(i, i + 128).map((e) => [`el:${e.id}`, e])));
      }
      this.broadcast({ type: 'update', elements: accepted }, ws);
      await this.ctx.storage.put('meta:editedAt', Date.now());
      return;
    }

    if (msg.type === 'file' && msg.file && validFile(msg.file as BoardFile)) {
      const f = msg.file as BoardFile;
      const file: BoardFile = { id: f.id, mimeType: f.mimeType, url: f.url, created: Date.now() };
      if ((await this.ctx.storage.get(`file:${f.id}`)) == null) {
        if ((await this.ctx.storage.list({ prefix: 'file:' })).size >= MAX_FILES) return;
        await this.ctx.storage.put(`file:${f.id}`, file);
      }
      this.broadcast({ type: 'file', file }, ws);
    }
  }

  async webSocketClose(ws: WebSocket, code: number) {
    try {
      ws.close(code === 1005 || code === 1006 ? 1000 : code);
    } catch {
      /* already closed */
    }
    this.broadcast({ type: 'peers', peers: this.presence().filter((p) => p.sid !== (ws.deserializeAttachment() as BoardPeer | null)?.sid) });
  }
}

function validElement(el: unknown): el is BoardElement {
  if (!el || typeof el !== 'object') return false;
  const e = el as BoardElement;
  if (typeof e.id !== 'string' || e.id.length > 64 || typeof e.version !== 'number' || typeof e.versionNonce !== 'number' || typeof e.type !== 'string') return false;
  // Pictures must point at an uploaded file, never carry the image inline.
  return JSON.stringify(e).length <= MAX_ELEMENT_BYTES;
}

function validFile(f: BoardFile): boolean {
  return (
    !!f && typeof f.id === 'string' && f.id.length <= 128 &&
    typeof f.mimeType === 'string' && /^image\/(png|jpeg|gif|webp|svg\+xml)$/.test(f.mimeType) &&
    typeof f.url === 'string' && f.url.length <= 600 &&
    // An upload of ours: database storage (/api/files/…) or the R2 files domain (https). Browsers
    // only load these from our own storage (BoardCanvas + the Content-Security-Policy).
    (/^\/api\/files\/[A-Za-z0-9_-]{16,}\/[^?#\s]*$/.test(f.url) || /^https:\/\/[a-z0-9.-]+\/[^\s"'<>]+$/i.test(f.url))
  );
}
